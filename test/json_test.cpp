    // Runs f and returns the json_parse_error it throws; fails if it throws nothing or something else.
    template<class F>
    json_parse_error catch_parse_error(F&& f, std::source_location location = std::source_location::current())
    {
        try {
            f();
        }
        catch (const json_parse_error& e) {
            return e;
        }
        gbassert(false, location);
        throw std::logic_error("unreachable");
    }

    // Serves the whole source through one get area that is never refilled, so the bytes a reader
    // actually extracted are exactly gptr() - eback().
    class extraction_streambuf : public std::streambuf
    {
    public:
        explicit extraction_streambuf(std::string source) : _source(std::move(source))
        {
            setg(_source.data(), _source.data(), _source.data() + _source.size());
        }

        [[nodiscard]] std::size_t extracted() const noexcept
        {
            return static_cast<std::size_t>(gptr() - eback());
        }

    private:
        std::string _source;
    };

    // Serves the source through underflow in 4 KiB chunks; extracted() is the bytes handed out
    // minus the bytes still unread in the current chunk.
    class chunked_streambuf : public std::streambuf
    {
    public:
        explicit chunked_streambuf(std::string source) : _source(std::move(source)) {}

        [[nodiscard]] std::size_t extracted() const noexcept
        {
            return _handed_out - static_cast<std::size_t>(egptr() - gptr());
        }

    protected:
        int_type underflow() override
        {
            if (gptr() < egptr())
                return traits_type::to_int_type(*gptr());
            if (_handed_out == _source.size())
                return traits_type::eof();
            auto n = std::min<std::size_t>(chunk, _source.size() - _handed_out);
            std::memcpy(_buffer, _source.data() + _handed_out, n);
            _handed_out += n;
            setg(_buffer, _buffer, _buffer + n);
            return traits_type::to_int_type(*gptr());
        }

    private:
        static constexpr std::size_t chunk = 4096;
        std::string _source;
        char _buffer[chunk]{};
        std::size_t _handed_out = 0;
    };

