    //-------------------------------------------------------------------------
    // errors
    //-------------------------------------------------------------------------
    enum class json_parse_errc
    {
        syntax,
        unexpected_end,
        control_character,
        invalid_escape,
        lone_surrogate,
        invalid_utf8,
        depth_exceeded,
        input_too_large,
        number_out_of_range,
        duplicate_key,
        handler_rejected
    };

    [[nodiscard]] constexpr std::string_view to_string(json_parse_errc value) noexcept
    {
        switch (value) {
        case json_parse_errc::syntax: return "syntax";
        case json_parse_errc::unexpected_end: return "unexpected_end";
        case json_parse_errc::control_character: return "control_character";
        case json_parse_errc::invalid_escape: return "invalid_escape";
        case json_parse_errc::lone_surrogate: return "lone_surrogate";
        case json_parse_errc::invalid_utf8: return "invalid_utf8";
        case json_parse_errc::depth_exceeded: return "depth_exceeded";
        case json_parse_errc::input_too_large: return "input_too_large";
        case json_parse_errc::number_out_of_range: return "number_out_of_range";
        case json_parse_errc::duplicate_key: return "duplicate_key";
        case json_parse_errc::handler_rejected: return "handler_rejected";
        }
        return "unknown";
    }

    struct json_parse_error : std::runtime_error
    {
        std::size_t offset = 0;
        std::uint32_t line = 0;
        std::uint32_t column = 0;
        json_parse_errc code = json_parse_errc::syntax;

        json_parse_error(std::string message, std::size_t offset, std::uint32_t line, std::uint32_t column,
            json_parse_errc code = json_parse_errc::syntax)
            : std::runtime_error(std::move(message)), offset(offset), line(line), column(column), code(code)
        {}
    };

    // Thrown by a handler to reject an event; the front end rethrows it as json_parse_error with the
    // position of the token that produced the event.
    struct json_handler_error : std::runtime_error
    {
        json_parse_errc code;

        json_handler_error(json_parse_errc code, std::string message)
            : std::runtime_error(std::move(message)), code(code)
        {}
    };

    //-------------------------------------------------------------------------
    // options and the handler interface
    //-------------------------------------------------------------------------
    enum class json_big_integer_policy
    {
        error,
        to_double
    };

    enum class json_duplicate_keys
    {
        reject,
        keep_first,
        keep_last
    };

    struct json_parse_options
    {
        std::size_t max_depth = 256;        // maximum number of simultaneously open containers
        std::size_t max_input_bytes = 0;    // 0 = unlimited
        json_big_integer_policy big_integers = json_big_integer_policy::error;
        bool allow_scalar_root = true;
        json_duplicate_keys duplicate_keys = json_duplicate_keys::reject;   // interpreted by handlers, not the front end
    };

    // A string or key view passed to a handler is valid only for the duration of the call.
    template<class H>
    concept json_handler = requires(H h, std::string_view s, bool b, std::int64_t i, std::uint64_t u, double d) {
        h.begin_object();
        h.end_object();
        h.key(s);
        h.begin_array();
        h.end_array();
        h.null_value();
        h.bool_value(b);
        h.int_value(i);
        h.uint_value(u);
        h.double_value(d);
        h.string_value(s);
    };

    //-------------------------------------------------------------------------
    // text utilities
    //-------------------------------------------------------------------------
    enum class json_invalid_utf8
    {
        error,
        replace     // U+FFFD for each maximal ill-formed subpart
    };

    struct json_escape_result
    {
        bool ok = true;
        std::size_t invalid_offset = 0;
    };

    namespace detail
    {
        struct utf8_decoded
        {
            char32_t code_point = 0;
            std::uint8_t length = 1;    // for an invalid sequence: the maximal subpart, at least 1
            bool valid = false;
        };

        // Decodes the UTF-8 sequence at s[i] per Unicode Table 3-7. The parser does not use this
        // to decide validity (axe::r_utf8 does); the writers use it to escape and validate output.
        [[nodiscard]] inline utf8_decoded utf8_decode(std::string_view s, std::size_t i) noexcept
        {
            auto byte = [&](std::size_t k) { return static_cast<unsigned char>(s[k]); };
            const auto b0 = byte(i);
            if (b0 < 0x80)
                return { b0, 1, true };

            std::size_t need = 0;
            unsigned char lo = 0x80, hi = 0xBF;
            char32_t cp = 0;
            if (b0 >= 0xC2 && b0 <= 0xDF) { need = 1; cp = b0 & 0x1Fu; }
            else if (b0 == 0xE0) { need = 2; lo = 0xA0; cp = b0 & 0x0Fu; }
            else if ((b0 >= 0xE1 && b0 <= 0xEC) || b0 == 0xEE || b0 == 0xEF) { need = 2; cp = b0 & 0x0Fu; }
            else if (b0 == 0xED) { need = 2; hi = 0x9F; cp = b0 & 0x0Fu; }
            else if (b0 == 0xF0) { need = 3; lo = 0x90; cp = b0 & 0x07u; }
            else if (b0 >= 0xF1 && b0 <= 0xF3) { need = 3; cp = b0 & 0x07u; }
            else if (b0 == 0xF4) { need = 3; hi = 0x8F; cp = b0 & 0x07u; }
            else
                return { 0, 1, false };

            std::uint8_t length = 1;
            for (std::size_t k = 1; k <= need; ++k, lo = 0x80, hi = 0xBF) {
                if (i + k >= s.size())
                    return { 0, length, false };
                const auto b = byte(i + k);
                if (b < lo || b > hi)
                    return { 0, length, false };
                cp = (cp << 6) | (b & 0x3Fu);
                ++length;
            }
            return { cp, length, true };
        }

        inline void append_utf8(char32_t code_point, std::string& out)
        {
            const auto cp = static_cast<std::uint32_t>(code_point);
            if (cp <= 0x7F) {
                out.push_back(static_cast<char>(cp));
            }
            else if (cp <= 0x7FF) {
                out.push_back(static_cast<char>(0xC0 | (cp >> 6)));
                out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
            }
            else if (cp <= 0xFFFF) {
                out.push_back(static_cast<char>(0xE0 | (cp >> 12)));
                out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
                out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
            }
            else {
                out.push_back(static_cast<char>(0xF0 | (cp >> 18)));
                out.push_back(static_cast<char>(0x80 | ((cp >> 12) & 0x3F)));
                out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
                out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
            }
        }

        inline void append_u_escape(std::uint32_t unit, std::string& out)
        {
            constexpr char digits[] = "0123456789abcdef";
            char buffer[6] = { '\\', 'u', digits[(unit >> 12) & 0xF], digits[(unit >> 8) & 0xF],
                digits[(unit >> 4) & 0xF], digits[unit & 0xF] };
            out.append(buffer, sizeof buffer);
        }

        struct json_position
        {
            std::uint32_t line = 1;
            std::uint32_t column = 1;
        };

        [[nodiscard]] inline json_position position_of(std::string_view text, std::size_t offset) noexcept
        {
            offset = std::min(offset, text.size());
            auto prefix = text.substr(0, offset);
            auto newlines = std::count(prefix.begin(), prefix.end(), '\n');
            auto last = prefix.rfind('\n');
            auto line_start = last == std::string_view::npos ? 0 : last + 1;
            return { static_cast<std::uint32_t>(newlines + 1), static_cast<std::uint32_t>(offset - line_start + 1) };
        }

        [[noreturn]] inline void throw_parse_error(std::string_view text, std::size_t offset, json_parse_errc code,
            std::string_view message)
        {
            auto position = position_of(text, offset);
            std::string what{ message };
            what += " (";
            what += container::to_string(code);
            what += ") at line ";
            what += std::to_string(position.line);
            what += ", column ";
            what += std::to_string(position.column);
            what += ", offset ";
            what += std::to_string(offset);
            throw json_parse_error(std::move(what), offset, position.line, position.column, code);
        }

        // Reads the whole stream, or throws input_too_large after extracting at most cap + 1 bytes
        // (cap == 0 means unlimited). A stream failure other than end of file throws runtime_error.
        [[nodiscard]] inline std::string read_capped(std::istream& in, std::size_t cap)
        {
            constexpr std::size_t chunk = 64 * 1024;
            std::string buffer;
            for (;;) {
                auto want = chunk;
                if (cap != 0) {
                    if (buffer.size() > cap)
                        break;
                    want = std::min(chunk, cap + 1 - buffer.size());
                }
                auto old_size = buffer.size();
                buffer.resize(old_size + want);
                in.read(buffer.data() + old_size, static_cast<std::streamsize>(want));
                auto got = static_cast<std::size_t>(in.gcount());
                buffer.resize(old_size + got);
                if (got < want)
                    break;
            }
            if (!in && !in.eof())
                throw std::runtime_error("Failed to read JSON stream");
            if (cap != 0 && buffer.size() > cap)
                throw_parse_error(buffer, cap, json_parse_errc::input_too_large,
                    "JSON input exceeds the maximum size of " + std::to_string(cap) + " bytes");
            return buffer;
        }
    }

    // Appends s to out as a quoted JSON string. On an ill-formed UTF-8 sequence with policy error,
    // out is left unchanged and the offset of the sequence within s is returned. Only allocation
    // failure throws.
    [[nodiscard]] inline json_escape_result append_json_string(std::string& out, std::string_view s,
        bool ascii_only, json_invalid_utf8 policy)
    {
        const auto original_size = out.size();
        out.push_back('"');
        std::size_t run_start = 0;
        std::size_t i = 0;
        auto flush = [&] { out.append(s.data() + run_start, i - run_start); };

        while (i < s.size()) {
            const auto c = static_cast<unsigned char>(s[i]);
            if (c < 0x80) {
                if (c >= 0x20 && c != '"' && c != '\\') {
                    ++i;
                    continue;
                }
                flush();
                switch (c) {
                case '"': out.append("\\\""); break;
                case '\\': out.append("\\\\"); break;
                case '\b': out.append("\\b"); break;
                case '\f': out.append("\\f"); break;
                case '\n': out.append("\\n"); break;
                case '\r': out.append("\\r"); break;
                case '\t': out.append("\\t"); break;
                default: detail::append_u_escape(c, out); break;
                }
                run_start = ++i;
                continue;
            }

            auto decoded = detail::utf8_decode(s, i);
            if (!decoded.valid) {
                if (policy == json_invalid_utf8::error) {
                    out.resize(original_size);
                    return { false, i };
                }
                flush();
                if (ascii_only)
                    detail::append_u_escape(0xFFFD, out);
                else
                    out.append("\xEF\xBF\xBD");
                i += decoded.length;
                run_start = i;
                continue;
            }
            if (ascii_only) {
                flush();
                auto cp = static_cast<std::uint32_t>(decoded.code_point);
                if (cp <= 0xFFFF) {
                    detail::append_u_escape(cp, out);
                }
                else {
                    cp -= 0x10000;
                    detail::append_u_escape(0xD800 + (cp >> 10), out);
                    detail::append_u_escape(0xDC00 + (cp & 0x3FF), out);
                }
                i += decoded.length;
                run_start = i;
                continue;
            }
            i += decoded.length;
        }
        flush();
        out.push_back('"');
        return {};
    }
