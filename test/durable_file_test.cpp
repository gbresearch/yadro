    GB_TEST(sha256, streaming_matches_one_shot)
    {
        std::vector<std::uint8_t> data(100'003);
        for (std::size_t i = 0; i < data.size(); ++i)
            data[i] = static_cast<std::uint8_t>(i * 131 + (i >> 7));
        auto expected = sha256digest(std::span<const std::uint8_t>{ data });

        sha256 hash;
        std::size_t offset = 0;
        for (std::size_t chunk = 1; offset < data.size(); chunk = chunk * 3 + 1) {
            auto size = std::min(chunk, data.size() - offset);
            hash.update(data.data() + offset, size);
            offset += size;
        }
        gbassert(hash.finalize().digest() == expected);
        gbassert(hash.to_string() == to_hex_string(std::span<const std::uint8_t>{ expected }));

        // byte at a time over a NIST vector, reusing the object after reset()
        hash.reset();
        for (char c : nist_896_bit)
            hash.update(std::string_view{ &c, 1 });
        gbassert(hash.finalize().to_string() == "cf5b16a778af8380036ce59e7b0492370b249b11e8f07a51afac45037afee9d1");

        must_throw<std::logic_error>([&] { hash.update("more"); });
        must_throw<std::logic_error>([] { [[maybe_unused]] auto d = sha256{}.update("abc").digest(); });
    }

