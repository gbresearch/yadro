//-----------------------------------------------------------------------------
// json_parser.h: the shared, hardened JSON front end and the text utilities that the
// JSON writers share.
//
// - json_parse_error / json_parse_errc: every parse failure carries a byte offset, a
//   1-based line and byte column (only LF advances the line), and a machine-readable code.
// - append_json_string: the string escaper used by both the json_value writer (json.h) and
//   the json_db writer (gbdb_json.h). It validates UTF-8 and never throws on bad input; it
//   reports the offset of the first ill-formed sequence or replaces each maximal ill-formed
//   subpart with U+FFFD.
// - detail::read_capped: reads a stream while never extracting more than cap + 1 bytes.
//-----------------------------------------------------------------------------

