    GB_TEST(json, json_read_capped_test)
    {
        std::string source;
        for (int i = 0; source.size() < 1024 * 1024; ++i)
            source += "line " + std::to_string(i) + " of the capped reader source\n";

        auto run = [&](auto& buffer, std::size_t cap) {
            std::istream in(&buffer);
            return jd::read_capped(in, cap);
        };

        {
            extraction_streambuf buffer(source);
            gbassert(run(buffer, 0) == source);
            gbassert(buffer.extracted() == source.size());
        }
        {
            chunked_streambuf buffer(source);
            gbassert(run(buffer, 0) == source);
            gbassert(buffer.extracted() == source.size());
        }
        {
            extraction_streambuf buffer(source);
            gbassert(run(buffer, source.size()) == source);
            gbassert(buffer.extracted() == source.size());
        }
        {
            chunked_streambuf buffer(source);
            gbassert(run(buffer, source.size()) == source);
        }
        for (std::size_t cap : { source.size() - 1, std::size_t{ 10 }, std::size_t{ 70'000 } }) {
            auto expected = jd::position_of(source, cap);
            {
                extraction_streambuf buffer(source);
                auto error = catch_parse_error([&] { (void)run(buffer, cap); });
                gbassert(error.code == json_parse_errc::input_too_large);
                gbassert(error.offset == cap);
                gbassert(error.line == expected.line && error.column == expected.column);
                gbassert(buffer.extracted() <= cap + 1);
            }
            {
                chunked_streambuf buffer(source);
                auto error = catch_parse_error([&] { (void)run(buffer, cap); });
                gbassert(error.code == json_parse_errc::input_too_large);
                gbassert(error.offset == cap);
                gbassert(buffer.extracted() <= cap + 1);
            }
        }

        {
            extraction_streambuf buffer(source);
            std::istream in(&buffer);
            in.setstate(std::ios::failbit);
            must_throw<std::runtime_error>([&] { (void)jd::read_capped(in, 0); });
        }
        {
            std::istringstream empty;
            gbassert(jd::read_capped(empty, 5).empty());
        }
    }

