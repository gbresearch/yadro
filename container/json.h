    namespace detail
    {
        [[nodiscard]] inline bool json_is_nonempty_container(const json_value& value) noexcept
        {
            if (auto* array = value.get_if<json_array>())
                return !array->empty();
            if (auto* object = value.get_if<json_object>())
                return !object->empty();
            return false;
        }

        [[nodiscard]] inline bool json_has_nested_container(const json_value& value) noexcept
        {
            if (auto* array = value.get_if<json_array>())
                return std::any_of(array->begin(), array->end(), json_is_nonempty_container);
            if (auto* object = value.get_if<json_object>())
                return std::any_of(object->begin(), object->end(), [](const json_member& m) { return json_is_nonempty_container(m.value); });
            return false;
        }

        // moves every non-empty container child of value to pending (a moved-from container is empty)
        inline void json_detach_nested(json_value& value, std::vector<json_value>& pending)
        {
            if (auto* array = value.get_if<json_array>()) {
                for (auto& element : *array)
                    if (json_is_nonempty_container(element))
                        pending.push_back(std::move(element));
            }
            else if (auto* object = value.get_if<json_object>()) {
                for (auto& member : *object)
                    if (json_is_nonempty_container(member.value))
                        pending.push_back(std::move(member.value));
            }
        }
    }

    // a copy of a scalar, or an empty container of the same kind
    inline json_value json_value::shallow_copy(const json_value& source)
    {
        json_value result;
        switch (source.kind()) {
        case json_kind::array:
            result._value.emplace<json_array>();
            break;
        case json_kind::object:
            result._value.emplace<json_object>();
            break;
        default:
            result._value = source._value;
            break;
        }
        return result;
    }

    // Copies nested containers one level at a time from a worklist, so copying a deeply nested
    // value takes no stack in proportion to its depth. Each container reserves its exact size
    // before its children are queued, so the queued target pointers stay valid.
    inline json_value::json_value(const json_value& other)
    {
        // a scalar, or a container whose children are scalars or empty containers: one level, no worklist
        if (!detail::json_has_nested_container(other)) {
            _value = other._value;
            return;
        }
        _value = shallow_copy(other)._value;
        std::vector<std::pair<const json_value*, json_value*>> pending{ { &other, this } };
        while (!pending.empty()) {
            auto [source, target] = pending.back();
            pending.pop_back();
            if (auto* from = source->get_if<json_array>()) {
                auto& to = *target->get_if<json_array>();
                to.reserve(from->size());
                for (auto& element : *from)
                    to.push_back(shallow_copy(element));
                for (std::size_t i = 0; i < from->size(); ++i)
                    if ((*from)[i].is_array() || (*from)[i].is_object())
                        pending.emplace_back(&(*from)[i], &to[i]);
            }
            else {
                auto& from_members = source->get_if<json_object>()->_members;
                auto& to_members = target->get_if<json_object>()->_members;
                to_members.reserve(from_members.size());
                for (auto& member : from_members)
                    to_members.push_back(json_member(member.key(), shallow_copy(member.value)));
                for (std::size_t i = 0; i < from_members.size(); ++i)
                    if (from_members[i].value.is_array() || from_members[i].value.is_object())
                        pending.emplace_back(&from_members[i].value, &to_members[i].value);
            }
        }
    }

    inline json_value& json_value::operator=(const json_value& other)
    {
        if (this != &other) {
            json_value copy(other);
            *this = std::move(copy);
        }
        return *this;
    }

    // Destroying nested containers recursively would take stack in proportion to the depth, several
    // KB per level in an unoptimized build. Instead, containers nested in containers are detached
    // into a worklist and destroyed one level at a time. If the worklist cannot be allocated, the
    // rest of the value is destroyed recursively.
    inline json_value::~json_value()
    {
        if (!detail::json_has_nested_container(*this))
            return;
        try {
            std::vector<json_value> pending;
            detail::json_detach_nested(*this, pending);
            while (!pending.empty()) {
                json_value current = std::move(pending.back());
                pending.pop_back();
                detail::json_detach_nested(current, pending);
            }
        }
        catch (...) {
        }
    }

    inline json_value::json_value(std::nullptr_t) noexcept {}
    inline json_value::json_value(bool value) noexcept : _value(std::in_place_type<bool>, value) {}

    template<std::integral T>
        requires (!std::same_as<T, bool> && !std::same_as<T, char> && !std::same_as<T, wchar_t>
            && !std::same_as<T, char8_t> && !std::same_as<T, char16_t> && !std::same_as<T, char32_t>)
    inline json_value::json_value(T value) noexcept
    {
        if constexpr (std::is_signed_v<T>) {
            _value.template emplace<std::int64_t>(static_cast<std::int64_t>(value));
        }
        else {
            const auto u = static_cast<std::uint64_t>(value);
            if (u <= static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max()))
                _value.template emplace<std::int64_t>(static_cast<std::int64_t>(u));
            else
                _value.template emplace<std::uint64_t>(u);
        }
    }

    inline json_value::json_value(double value) noexcept : _value(std::in_place_type<double>, value) {}
    inline json_value::json_value(float value) noexcept : _value(std::in_place_type<double>, static_cast<double>(value)) {}
    inline json_value::json_value(std::string value) noexcept : _value(std::in_place_type<std::string>, std::move(value)) {}
    inline json_value::json_value(std::string_view value) : _value(std::in_place_type<std::string>, value) {}
    inline json_value::json_value(const char* value)
    {
        if (!value)
            throw std::invalid_argument("json_value cannot be constructed from a null const char*");
        _value.emplace<std::string>(value);
    }
    inline json_value::json_value(json_array value) noexcept : _value(std::in_place_type<json_array>, std::move(value)) {}
    inline json_value::json_value(json_object value) noexcept : _value(std::in_place_type<json_object>, std::move(value)) {}

    inline json_kind json_value::kind() const noexcept { return static_cast<json_kind>(_value.index()); }
    inline bool json_value::is_null() const noexcept { return kind() == json_kind::null; }
    inline bool json_value::is_bool() const noexcept { return kind() == json_kind::boolean; }
    inline bool json_value::is_integer() const noexcept { return kind() == json_kind::int64 || kind() == json_kind::uint64; }
    inline bool json_value::is_number() const noexcept { return is_integer() || kind() == json_kind::number; }
    inline bool json_value::is_string() const noexcept { return kind() == json_kind::string; }
    inline bool json_value::is_array() const noexcept { return kind() == json_kind::array; }
    inline bool json_value::is_object() const noexcept { return kind() == json_kind::object; }

    namespace detail
    {
        template<class T>
        inline constexpr bool is_json_alternative = std::same_as<T, bool> || std::same_as<T, std::int64_t>
            || std::same_as<T, std::uint64_t> || std::same_as<T, double> || std::same_as<T, std::string>
            || std::same_as<T, json_array> || std::same_as<T, json_object>;
    }

    template<class T>
    inline T* json_value::get_if() noexcept
    {
        static_assert(detail::is_json_alternative<T>, "json_value::get_if: T must be one of the stored kinds");
        return std::get_if<T>(&_value);
    }

    template<class T>
    inline const T* json_value::get_if() const noexcept
    {
        static_assert(detail::is_json_alternative<T>, "json_value::get_if: T must be one of the stored kinds");
        return std::get_if<T>(&_value);
    }

    inline json_access_error json_value::mismatch() const noexcept
    {
        return { json_access_error::reason::type_mismatch, kind() };
    }

    inline std::expected<bool, json_access_error> json_value::as_bool() const noexcept
    {
        if (auto* b = std::get_if<bool>(&_value))
            return *b;
        return std::unexpected(mismatch());
    }

    inline std::expected<std::int64_t, json_access_error> json_value::as_int64() const noexcept
    {
        if (auto* i = std::get_if<std::int64_t>(&_value))
            return *i;
        if (std::holds_alternative<std::uint64_t>(_value))
            return std::unexpected(json_access_error{ json_access_error::reason::out_of_range, json_kind::uint64 });
        return std::unexpected(mismatch());
    }

    inline std::expected<std::uint64_t, json_access_error> json_value::as_uint64() const noexcept
    {
        if (auto* u = std::get_if<std::uint64_t>(&_value))
            return *u;
        if (auto* i = std::get_if<std::int64_t>(&_value)) {
            if (*i >= 0)
                return static_cast<std::uint64_t>(*i);
            return std::unexpected(json_access_error{ json_access_error::reason::out_of_range, json_kind::int64 });
        }
        return std::unexpected(mismatch());
    }

    inline std::expected<double, json_access_error> json_value::as_double() const noexcept
    {
        if (auto* d = std::get_if<double>(&_value))
            return *d;
        if (auto* i = std::get_if<std::int64_t>(&_value))
            return static_cast<double>(*i);
        if (auto* u = std::get_if<std::uint64_t>(&_value))
            return static_cast<double>(*u);
        return std::unexpected(mismatch());
    }

    inline std::expected<std::string_view, json_access_error> json_value::as_string() const noexcept
    {
        if (auto* s = std::get_if<std::string>(&_value))
            return std::string_view{ *s };
        return std::unexpected(mismatch());
    }

    inline std::expected<const json_array*, json_access_error> json_value::as_array() const noexcept
    {
        if (auto* a = std::get_if<json_array>(&_value))
            return a;
        return std::unexpected(mismatch());
    }

    inline std::expected<json_array*, json_access_error> json_value::as_array() noexcept
    {
        if (auto* a = std::get_if<json_array>(&_value))
            return a;
        return std::unexpected(mismatch());
    }

    inline std::expected<const json_object*, json_access_error> json_value::as_object() const noexcept
    {
        if (auto* o = std::get_if<json_object>(&_value))
            return o;
        return std::unexpected(mismatch());
    }

    inline std::expected<json_object*, json_access_error> json_value::as_object() noexcept
    {
        if (auto* o = std::get_if<json_object>(&_value))
            return o;
        return std::unexpected(mismatch());
    }

    //-------------------------------------------------------------------------
    // equality
    //-------------------------------------------------------------------------
    namespace detail
    {
        // exact comparisons: the double must be finite, integral and inside the integer's range
        [[nodiscard]] inline bool json_equals(std::int64_t i, double d) noexcept
        {
            if (!std::isfinite(d) || std::trunc(d) != d || d < -9223372036854775808.0 || d >= 9223372036854775808.0)
                return false;
            return static_cast<std::int64_t>(d) == i;
        }

        [[nodiscard]] inline bool json_equals(std::uint64_t u, double d) noexcept
        {
            if (!std::isfinite(d) || std::trunc(d) != d || d < 0.0 || d >= 18446744073709551616.0)
                return false;
            return static_cast<std::uint64_t>(d) == u;
        }

        [[nodiscard]] inline bool json_equals(std::int64_t i, std::uint64_t u) noexcept
        {
            return i >= 0 && static_cast<std::uint64_t>(i) == u;
        }
    }

    namespace detail
    {
        using json_value_pairs = std::vector<std::pair<const json_value*, const json_value*>>;

        // Compares two numbers of any numeric kinds exactly.
        [[nodiscard]] inline bool json_numbers_equal(const json_value& a, const json_value& b) noexcept
        {
            if (auto* x = a.get_if<std::int64_t>()) {
                if (auto* y = b.get_if<std::int64_t>())
                    return *x == *y;
                if (auto* y = b.get_if<std::uint64_t>())
                    return json_equals(*x, *y);
                return json_equals(*x, *b.get_if<double>());
            }
            if (auto* x = a.get_if<std::uint64_t>()) {
                if (auto* y = b.get_if<std::uint64_t>())
                    return *x == *y;
                if (auto* y = b.get_if<std::int64_t>())
                    return json_equals(*y, *x);
                return json_equals(*x, *b.get_if<double>());
            }
            const double x = *a.get_if<double>();
            if (auto* y = b.get_if<double>())
                return x == *y;
            if (auto* y = b.get_if<std::int64_t>())
                return json_equals(*y, x);
            return json_equals(*b.get_if<std::uint64_t>(), x);
        }

        // Compares a and b and their direct leaf children; pairs involving a child container are
        // queued in pending (object members are matched by key, order ignored). Not recursive, and
        // flat containers never allocate.
        [[nodiscard]] inline bool json_node_equal(const json_value& a, const json_value& b, json_value_pairs& pending);

        // compares two leaves now, or queues a pair that involves a container
        [[nodiscard]] inline bool json_child_equal(const json_value& a, const json_value& b, json_value_pairs& pending)
        {
            if (a.is_array() || a.is_object() || b.is_array() || b.is_object()) {
                pending.emplace_back(&a, &b);
                return true;
            }
            return json_node_equal(a, b, pending);
        }

        inline bool json_node_equal(const json_value& a, const json_value& b, json_value_pairs& pending)
        {
            if (a.is_number() || b.is_number())
                return a.is_number() && b.is_number() && json_numbers_equal(a, b);
            if (a.kind() != b.kind())
                return false;
            switch (a.kind()) {
            case json_kind::null:
                return true;
            case json_kind::boolean:
                return *a.get_if<bool>() == *b.get_if<bool>();
            case json_kind::string:
                return *a.get_if<std::string>() == *b.get_if<std::string>();
            case json_kind::array: {
                auto& x = *a.get_if<json_array>();
                auto& y = *b.get_if<json_array>();
                if (x.size() != y.size())
                    return false;
                for (std::size_t i = 0; i < x.size(); ++i)
                    if (!json_child_equal(x[i], y[i], pending))
                        return false;
                return true;
            }
            case json_kind::object: {
                auto& x = *a.get_if<json_object>();
                auto& y = *b.get_if<json_object>();
                if (x.size() != y.size())
                    return false;
                if (x.size() <= 16) {
                    for (auto& member : x) {
                        auto* other = y.find(member.key());
                        if (!other || !json_child_equal(member.value, *other, pending))
                            return false;
                    }
                    return true;
                }
                auto sorted = [](const json_object& o) {
                    std::vector<const json_member*> members;
                    members.reserve(o.size());
                    for (auto& member : o)
                        members.push_back(&member);
                    std::sort(members.begin(), members.end(), [](const json_member* p, const json_member* q) { return p->key() < q->key(); });
                    return members;
                };
                auto sx = sorted(x);
                auto sy = sorted(y);
                for (std::size_t i = 0; i < sx.size(); ++i) {
                    if (sx[i]->key() != sy[i]->key() || !json_child_equal(sx[i]->value, sy[i]->value, pending))
                        return false;
                }
                return true;
            }
            default:
                return false;
            }
        }
    }

    // Iterative, so comparing deeply nested values takes no stack in proportion to their depth.
    inline bool operator==(const json_value& a, const json_value& b)
    {
        detail::json_value_pairs pending;
        const json_value* x = &a;
        const json_value* y = &b;
        for (;;) {
            if (!detail::json_node_equal(*x, *y, pending))
                return false;
            if (pending.empty())
                return true;
            std::tie(x, y) = pending.back();
            pending.pop_back();
        }
    }

