#pragma once

// SHA-256 (FIPS 180-4) through Windows CNG (bcrypt.dll), plus hex helpers.
//
//   sha256                      streaming hash: update(...) any number of times, finalize(),
//                               then digest() / to_string(); reset() starts over
//   sha256digest(bytes)         one-shot digest of a byte span or string
//   sha256string(bytes)         the same as lowercase hex
//   sha256_file_digest(path)    digest of a file's content
//   sha256_file_string(path)    the same as lowercase hex
//   to_hex_string(bytes)        lowercase (or uppercase) hex of any bytes
//   parse_sha256_hex(text)      64 hex digits back to a digest, or nullopt
//
// The hash is Windows-only (the hex helpers are portable). CNG failures throw cng_error
// (exception_t<long>, data() = NTSTATUS); file I/O failures throw file_io_error.
//
// Thread safety: the SHA-256 algorithm provider is opened once per process, on first use
// (thread-safe static initialization), cached, and closed during static destruction; do not
// hash from destructors of other static objects. CNG allows one algorithm handle to be used
// by several threads at once, which is all the cache does (BCryptCreateHash). Each sha256
// object owns its own CNG hash handle and, like any mutable object, must not be used by two
// threads at the same time.

#include "durable_file.h"

