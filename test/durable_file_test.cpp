    GB_TEST(durable_file, append_only_file_append_flush_reopen)
    {
        auto directory = fresh_test_directory("append");
        auto file = directory / "journal.log";
        {
            append_only_file journal(file, append_only_file::open_mode::create_new);
            gbassert(journal.is_open());
            gbassert(journal.size() == 0);
            journal.append("abc");
            journal.append(std::as_bytes(std::span{ std::string_view{ "defg" } }));
            gbassert(journal.size() == 7);
            journal.flush();
        }
        gbassert(read_whole_file(file) == "abcdefg");

        append_only_file journal(file, append_only_file::open_mode::open_existing);
        gbassert(journal.size() == 7);
        journal.append("h");
        journal.flush();
        gbassert(journal.size() == 8);

        std::array<std::byte, 16> buffer{};
        gbassert(journal.read_at(0, buffer) == 8);
        gbassert(std::string_view(reinterpret_cast<const char*>(buffer.data()), 8) == "abcdefgh");
        gbassert(journal.read_at(6, buffer) == 2);
        gbassert(journal.read_at(8, buffer) == 0);
        gbassert(journal.read_at(100, buffer) == 0);

        // readers may open the journal while it is being written
        gbassert(read_whole_file(file) == "abcdefgh");

        journal.close();
        gbassert(!journal.is_open());
        gbassert(read_whole_file(file) == "abcdefgh");
        fs::remove_all(directory);
    }

    GB_TEST(durable_file, append_only_file_truncate_torn_tail)
    {
        auto directory = fresh_test_directory("truncate");
        auto file = directory / "journal.log";
        {
            append_only_file journal(file);
            journal.append("rec1;rec2;");
            journal.append("rec3-torn"); // a record whose terminator never made it
            journal.flush();
        }

        // recovery: scan for the end of the last complete record and cut there
        append_only_file journal(file);
        std::vector<std::byte> content(static_cast<std::size_t>(journal.size()));
        gbassert(journal.read_at(0, content) == content.size());
        std::uint64_t valid_end = 0;
        for (std::size_t i = 0; i < content.size(); ++i)
            if (content[i] == std::byte{ ';' })
                valid_end = i + 1;
        gbassert(valid_end == 10);

        journal.truncate_to(valid_end);
        gbassert(journal.size() == 10);
        journal.append("rec3;");
        journal.flush();
        gbassert(journal.size() == 15);
        gbassert(read_whole_file(file) == "rec1;rec2;rec3;");

        gbassert(file_io_error_code([&] { journal.truncate_to(16); }) == std::errc::invalid_argument);
        journal.truncate_to(0);
        gbassert(journal.size() == 0);
        gbassert(read_whole_file(file).empty());
        journal.close();
        fs::remove_all(directory);
    }

