namespace gb::yadro::util
{
    //-------------------------------------------------------------------------
    [[nodiscard]] inline std::string to_hex_string(std::span<const std::byte> bytes, bool uppercase = false)
    {
        constexpr std::string_view lower_digits = "0123456789abcdef";
        constexpr std::string_view upper_digits = "0123456789ABCDEF";
        auto digits = uppercase ? upper_digits : lower_digits;

        std::string result(bytes.size() * 2, '\0');
        for (std::size_t i = 0; i < bytes.size(); ++i) {
            auto value = std::to_integer<unsigned>(bytes[i]);
            result[2 * i] = digits[value >> 4];
            result[2 * i + 1] = digits[value & 0x0f];
        }
        return result;
    }

    [[nodiscard]] inline std::string to_hex_string(std::span<const std::uint8_t> bytes, bool uppercase = false)
    {
        return to_hex_string(std::as_bytes(bytes), uppercase);
    }

    namespace detail
    {
        [[nodiscard]] constexpr int hex_digit_value(char c) noexcept
        {
            return c >= '0' && c <= '9' ? c - '0'
                : c >= 'a' && c <= 'f' ? c - 'a' + 10
                : c >= 'A' && c <= 'F' ? c - 'A' + 10
                : -1;
        }
    }

    // decodes exactly out.size() bytes from 2 * out.size() hex digits (either case)
    [[nodiscard]] inline bool from_hex_string(std::string_view text, std::span<std::uint8_t> out) noexcept
    {
        if (text.size() != out.size() * 2)
            return false;
        for (std::size_t i = 0; i < out.size(); ++i) {
            auto high = detail::hex_digit_value(text[2 * i]);
            auto low = detail::hex_digit_value(text[2 * i + 1]);
            if (high < 0 || low < 0)
                return false;
            out[i] = static_cast<std::uint8_t>(high << 4 | low);
        }
        return true;
    }
}

