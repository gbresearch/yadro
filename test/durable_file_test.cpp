    fs::path fresh_test_directory(std::string_view name)
    {
        auto directory = fs::temp_directory_path() / "yadro_durable_file_test" / name;
        fs::remove_all(directory);
        fs::create_directories(directory);
        return directory;
    }

    std::string read_whole_file(const fs::path& file)
    {
        std::ifstream in(file, std::ios::binary);
        return std::string((std::istreambuf_iterator<char>(in)), {});
    }

    void write_whole_file(const fs::path& file, std::string_view text)
    {
        std::ofstream out(file, std::ios::binary);
        out.write(text.data(), static_cast<std::streamsize>(text.size()));
    }

    std::size_t count_temp_files(const fs::path& directory)
    {
        std::size_t count = 0;
        for (auto&& entry : fs::directory_iterator(directory))
            if (entry.path().extension() == ".tmp")
                ++count;
        return count;
    }

    // the error code of the file_io_error fn throws, or an empty code if it throws nothing
    template<class Fn>
    std::error_code file_io_error_code(Fn&& fn)
    {
        try {
            fn();
        }
        catch (const file_io_error& e) {
            return e.data();
        }
        return {};
    }

    // how an atomic_replace_file call ended, and with which error code
    enum class replace_outcome { replaced, not_committed, committed_not_durable, unknown };

    template<class Fn>
    std::pair<replace_outcome, std::error_code> replace_result(Fn&& fn)
    {
        try {
            fn();
        }
        catch (const replace_not_durable_error& e) {
            return { replace_outcome::committed_not_durable, e.data() };
        }
        catch (const replace_outcome_unknown_error& e) {
            return { replace_outcome::unknown, e.data() };
        }
        catch (const file_io_error& e) {
            return { replace_outcome::not_committed, e.data() };
        }
        return { replace_outcome::replaced, {} };
    }

