    struct winpipe_client_t : winpipe_base_t
    {
        // anonymous client
        winpipe_client_t(const std::wstring& pipename, unsigned connection_attempts, auto&& ...log_args) // Win10, v 1709 "\\\\.\\pipe\\LOCAL\\"
            : winpipe_client_t(pipename, "", connection_attempts, std::forward<decltype(log_args)>(log_args)...)
        {}
        
        template<class Rep, class Period>
        winpipe_client_t(const std::wstring& pipename, std::chrono::duration<Rep, Period> timeout, unsigned connection_attempts, 
            auto&& ...log_args) // Win10, v 1709 "\\\\.\\pipe\\LOCAL\\"
            : winpipe_client_t(pipename, "", timeout, connection_attempts, std::forward<decltype(log_args)>(log_args)...)
        {}

        // named client
        winpipe_client_t(const std::wstring& pipename, std::string client_name, unsigned connection_attempts, auto&& ...log_args) // Win10, v 1709 "\\\\.\\pipe\\LOCAL\\"
            : winpipe_client_t(pipename, std::move(client_name), std::chrono::milliseconds(pipe_io_timeout_ms), connection_attempts, std::forward<decltype(log_args)>(log_args)...)
        {}

        template<class Rep, class Period>
        winpipe_client_t(const std::wstring& pipename, std::string client_name, std::chrono::duration<Rep, Period> timeout,
            unsigned connection_attempts, auto&&... log_args)
            : winpipe_client_t(pipename, pipe_client_options{}, std::move(client_name), timeout, connection_attempts,
                std::forward<decltype(log_args)>(log_args)...)
        {}

        // named client with explicit options, see pipe_client_options
        winpipe_client_t(const std::wstring& pipename, const pipe_client_options& options, std::string client_name,
            unsigned connection_attempts, auto&& ...log_args)
            : winpipe_client_t(pipename, options, std::move(client_name), std::chrono::milliseconds(pipe_io_timeout_ms),
                connection_attempts, std::forward<decltype(log_args)>(log_args)...)
        {}

        template<class Rep, class Period>
        winpipe_client_t(const std::wstring& pipename, const pipe_client_options& options, std::string client_name,
            std::chrono::duration<Rep, Period> timeout, unsigned connection_attempts, auto&&... log_args)
            : winpipe_base_t(timeout, std::forward<decltype(log_args)>(log_args)...), _client_name(std::move(client_name))
        {
            const pipe_server_verifier verifier{ options };
            // Windows' default without SECURITY_SQOS_PRESENT is full impersonation
            const DWORD sqos_flags = options.allow_impersonation ? 0 : SECURITY_SQOS_PRESENT | SECURITY_IDENTIFICATION;
            using namespace std::chrono_literals;
            auto attempt = 0u;
            for (; _pipe == INVALID_HANDLE_VALUE && attempt < connection_attempts; ++attempt)
            {
                if (attempt != 0)
                    std::this_thread::sleep_for(10ms);

                // wait upto 50ms for pipe instance to become available, exits immediately if no active server
                if (WaitNamedPipe(pipename.c_str(), 50))
                {
                    // try to grab a pipe, other client can frontrun, so CreateFile can fail
                    _pipe = CreateFile(
                        pipename.c_str(),
                        pipe_client_access, // read, write data and attributes; not GENERIC_WRITE
                        0,              // no sharing 
                        nullptr,        // default security attributes
                        OPEN_EXISTING,  // opens existing pipe 
                        FILE_FLAG_OVERLAPPED | sqos_flags,
                        nullptr);       // no template file 
                }
            }

            if (_pipe == INVALID_HANDLE_VALUE)
            {
                auto str_name = pipe_name_for_error(pipename);
                auto error_string = util::to_string("\"", _client_name, "\": failed to open pipe: ", str_name, ": ", GetLastError());
                log(error_string);
                throw util::exception_t(error_string);
            }

            // opt-in, before anything is sent: see pipe_client_options for the limits of this check
            if (auto reason = verifier.mismatch(_pipe); !reason.empty())
            {
                auto str_name = pipe_name_for_error(pipename);
                auto error_string = util::to_string("\"", _client_name, "\": pipe server identity check failed: ", str_name, ": ", reason);
                log(error_string);
                _pipe.reset(); // close without the disconnect notification: nothing goes to this server
                throw util::exception_t(error_string);
            }

            // The pipe connected; keep byte-read mode. Top-level send/receive calls provide framing.
            if (DWORD mode = PIPE_READMODE_BYTE; not SetNamedPipeHandleState(
                _pipe,    // pipe handle 
                &mode,  // new pipe mode 
                nullptr,     // don't set maximum bytes 
                nullptr))    // don't set maximum time 
            {
                auto str_name = pipe_name_for_error(pipename);
                auto error_string = util::to_string("\"", _client_name, "\":  pipe: ", str_name, ": SetNamedPipeHandleState failed: ", GetLastError());
                log(error_string);
                throw util::exception_t(error_string);
            }

            log("\"", _client_name, "\": opened pipe after ", attempt, " attempts");
        }

        ~winpipe_client_t() noexcept
        {
            try { log("\"", _client_name, "\": destructor"); }
            catch (...) {}
            disconnect();
        }

        template<class T>
        [[nodiscard]]
        auto request(const std::string& name, auto&& ...params) const
        {
            std::scoped_lock lock(_mutex);
            log("\"", _client_name, "\": sending request for function: ", name);
            // one coalesced write: call_id(0) + name + params, framed identically to three sends
            send_frames(0u, name, std::tuple{ std::forward<decltype(params)>(params)... });
            return receive<std::expected<T, std::string>>();
        }

        template<class T>
        [[nodiscard]]
        auto request(std::uint32_t fn_id, auto&& ...params) const
        {
            std::scoped_lock lock(_mutex);
            log("\"", _client_name, "\": sending request");
            send_frames(fn_id, std::tuple{ std::forward<decltype(params)>(params)... });
            return receive<std::expected<T, std::string>>();
        }

        template<auto Index, class T>
        [[nodiscard]]
        auto request(auto&& ...params) const
        {
            return request<T>(Index, std::forward<decltype(params)>(params)...);
        }

        void disconnect() noexcept
        {
            close_pipe(server_disconnect, "disconnect");
        }

        void shutdown() noexcept
        {
            close_pipe(server_shutdown, "shutdown");
        }

        auto&& get_name() const { return _client_name; }

    private:
        void close_pipe(std::uint32_t message, const char* action) noexcept
        {
            std::scoped_lock lock(_mutex);

            if (!_pipe.valid())
                return;

            try
            {
                send<std::uint32_t>(message);
            }
            catch (std::exception& e)
            {
                try { log("\"", _client_name, "\": ", action, " notification failed: ", e.what()); }
                catch (...) {}
            }
            catch (...)
            {
                try { log("\"", _client_name, "\": ", action, " notification failed with unknown exception"); }
                catch (...) {}
            }

            _pipe.reset();
        }

        std::string _client_name;
        mutable std::mutex _mutex;
    };

