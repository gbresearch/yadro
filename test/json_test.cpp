    GB_TEST(json, json_parse_error_compat_test)
    {
        json_parse_error legacy("message", 7, 2, 3);
        gbassert(legacy.offset == 7 && legacy.line == 2 && legacy.column == 3);
        gbassert(legacy.code == json_parse_errc::syntax);
        gbassert(std::string_view{ legacy.what() } == "message");

        json_parse_error coded("message", 1, 1, 2, json_parse_errc::invalid_utf8);
        gbassert(coded.code == json_parse_errc::invalid_utf8);

        std::set<std::string_view> names;
        for (auto code : { json_parse_errc::syntax, json_parse_errc::unexpected_end, json_parse_errc::control_character,
                 json_parse_errc::invalid_escape, json_parse_errc::lone_surrogate, json_parse_errc::invalid_utf8,
                 json_parse_errc::depth_exceeded, json_parse_errc::input_too_large, json_parse_errc::number_out_of_range,
                 json_parse_errc::duplicate_key, json_parse_errc::handler_rejected }) {
            auto name = gb::yadro::container::to_string(code);
            gbassert(!name.empty());
            names.insert(name);
        }
        gbassert(names.size() == 11);

        json_handler_error handler_error(json_parse_errc::duplicate_key, "dup");
        gbassert(handler_error.code == json_parse_errc::duplicate_key);
        gbassert(std::string_view{ handler_error.what() } == "dup");
    }

    GB_TEST(json, json_escape_basic_test)
    {
        gbassert(escape("a\"b\\c/\b\f\n\r\t\x01\x1f\x7f") == "\"a\\\"b\\\\c/\\b\\f\\n\\r\\t\\u0001\\u001f\x7f\"");
        gbassert(escape("") == "\"\"");
        gbassert(escape(std::string_view{ "\0", 1 }) == "\"\\u0000\"");

        const std::string_view text = "\xC3\xA9\xF0\x9F\x98\x80";   // U+00E9 U+1F600
        gbassert(escape(text) == "\"" + std::string{ text } + "\"");
        gbassert(escape(text, true) == "\"\\u00e9\\ud83d\\ude00\"");

        // boundaries of each encoding length
        gbassert(escape("\xC2\x80", true) == "\"\\u0080\"");
        gbassert(escape("\xDF\xBF", true) == "\"\\u07ff\"");
        gbassert(escape("\xE0\xA0\x80", true) == "\"\\u0800\"");
        gbassert(escape("\xEF\xBF\xBF", true) == "\"\\uffff\"");
        gbassert(escape("\xF0\x90\x80\x80", true) == "\"\\ud800\\udc00\"");
        gbassert(escape("\xF4\x8F\xBF\xBF", true) == "\"\\udbff\\udfff\"");

        // appends rather than replacing
        std::string out = "prefix:";
        gbassert(append_json_string(out, "x", false, json_invalid_utf8::error).ok);
        gbassert(out == "prefix:\"x\"");
    }

    GB_TEST(json, json_escape_invalid_utf8_test)
    {
        struct invalid_case { std::string_view input; std::size_t offset; };
        for (auto [input, offset] : { invalid_case{ "ab\xC0\xAF", 2 }, invalid_case{ "x\xED\xA0\x80", 1 },
                 invalid_case{ "\xF4\x90\x80\x80", 0 }, invalid_case{ "ok\xE2\x82", 2 }, invalid_case{ "\x80", 0 },
                 invalid_case{ "\xFF", 0 }, invalid_case{ "\xF5\x80\x80\x80", 0 }, invalid_case{ "\xE0\x80\x80", 0 } }) {
            for (bool ascii_only : { false, true }) {
                std::string out = "keep";
                auto result = append_json_string(out, input, ascii_only, json_invalid_utf8::error);
                gbassert(!result.ok);
                gbassert(result.invalid_offset == offset);
                gbassert(out == "keep");   // unchanged on failure
            }
        }

        auto replaced = [](std::string_view input, bool ascii_only) {
            std::string out;
            auto result = append_json_string(out, input, ascii_only, json_invalid_utf8::replace);
            gbassert(result.ok);
            return out;
        };
        // E2 82 is one maximal subpart; the literal is split because \x82A would be one hex escape
        gbassert(replaced("\xE2\x82" "A", false) == "\"\xEF\xBF\xBD" "A\"");
        gbassert(replaced("\xC0\xAF", false) == "\"\xEF\xBF\xBD\xEF\xBF\xBD\"");
        gbassert(replaced("\xED\xA0\x80", false) == "\"\xEF\xBF\xBD\xEF\xBF\xBD\xEF\xBF\xBD\"");
        gbassert(replaced("\xF0\x9F\x98", false) == "\"\xEF\xBF\xBD\"");
        gbassert(replaced("\xE2\x82" "A", true) == "\"\\ufffdA\"");
    }

