#include "../include/yadro.h"
#include <thread>
#include <chrono>

#pragma comment(lib, "yadro")

int main(int argc, char* argv[])
{
    using namespace gb::yadro::util;

#if defined(GBWINDOWS)
    // Child mode for the abandoned-mutex tests, dispatched before any test setup because it must
    // die while still owning the mutex. A mutex is only abandoned when its owner exits WITHOUT
    // releasing it, which no ordinary test can produce: unwinding a global_mutex releases it. So
    // the child locks, signals its parent, and calls ExitProcess so that no destructor runs.
    if (argc == 4 && argv[1] == std::string("--abandon-global-mutex"))
    {
        global_mutex mutex{ std::string{ argv[2] } };
        mutex.lock();
        if (unique_win_handle ready{ OpenEventA(EVENT_MODIFY_STATE, FALSE, argv[3]) };
            ready.valid())
        {
            SetEvent(ready.get());
        }
        else
        {
            return -1;
        }
        ExitProcess(0);
    }
#endif

    tester::set_verbose(true);
    tester::set_logger("yadro-test.log", std::cout);
#ifndef GBWINDOWS
    tester::disable_tests("util", "win_pipe1");
    tester::disable_tests("util", "win_pipe2");
    tester::disable_tests("util", "win_pipe3");
#else
    if (argc < 2 || argv[1] != std::string("--run-all"))
    {
        tester::disable_tests("container", "gbdb_registry_win32_integration_test");
    }
#endif
    if (argc < 2 || argv[1] != std::string("--run-all"))
    {
        // bounded_priority_queue_test is disabled by default because it fails on slow machines
        tester::disable_tests("container", "bounded_priority_queue_test");
    }
    
    tester::set_policy(std::launch::deferred);
    auto success = tester::run();
    return success ? 0 : -1;
}
